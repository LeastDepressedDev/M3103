/**
 * Алгоритм: Сортировка пузырьком (Bubble Sort)
 * Тип: Сортировка (стабильная, если делать правильно; тут — не совсем, но об этом ниже)
 * 
 * Скорость: O(n^2) — и это не случайность, это приговор
 * Память: O(1) — вообще ничего не выделяем, красота
 * 
 * Так, народ. Вот мы и добрались до самой позорной сортировки в этом курсе. Пузырёк.
 * 
 * Если merge_sort — это профессор, quick_sort — это хулиган, count_sort — это читер,
 * то bubble_sort — это тот чувак, который на паре спит, а потом говорит "я всё понял".
 * 
 * Идея: проходим по массиву и сравниваем СОСЕДНИЕ элементы. Если левый больше правого — меняем их местами.
 * Прошли один раз — самый большой элемент "всплыл" в конец, как пузырёк воздуха в воде. Отсюда и название.
 * Прошли второй раз — второй по величине всплыл на своё место. И так n раз. Профит.
 * 
 * Почему O(n^2)? Потому что два вложенных цикла, каждый до n. n * n = n^2. Всё.
 * И это не "в среднем", не "в худшем" — это ВСЕГДА. Даже если массив уже отсортирован,
 * мы всё равно пройдёмся n^2 раз, потому что нам лень добавить флаг "были ли обмены".
 * Хотя могли бы — и тогда на отсортированном массиве было бы O(n). Но кто ж нас учил.
 * 
 * Стабильность: классический пузырёк СТАБИЛЕН, если менять только когда arr[j] > arr[j+1] (строго больше).
 * Тогда равные элементы не меняются местами. НО. В этой конкретной реализации используется
 * сравнение arr[i] < arr[j] для ВСЕХ пар i, j — включая далёкие друг от друга. Это не пузырёк,
 * это какой-то монстр. Он делает n^2 сравнений и n^2 обменов, и он НЕстабилен, потому что
 * меняет местами элементы, которые не являются соседями. Так что формально — это даже не совсем пузырёк.
 * Это "сортировка двойным циклом", которая работает, но вызывает боль у всех, кто её видит.
 * 
 * Кстати, если тебе интересно, почему такой вариант всё-таки сортирует: на каждом шаге внешнего цикла i
 * мы гарантированно ставим arr[i] на его место. Как? Потому что во внутреннем цикле мы сравниваем arr[i]
 * со ВСЕМИ остальными и меняем, если arr[i] меньше. После полного прохода j от 0 до n-1,
 * arr[i] становится минимальным среди arr[i..n-1]. Потом i++ и повторяем. Это работает, но это
 * О(n^2) обменов, что в разы хуже, чем у нормального пузырька (O(n^2) сравнений, но O(n^2) обменов в худшем,
 * а в среднем — O(n^2) сравнений и O(n^2) обменов, лол, всё равно плохо).
 * 
 * Вердикт: используй только для обучения. Или для массивов длиной 5. Или для собеседования,
 * где просят написать что-то простое. В продакшене — никогда. Никогда-никогда.
 */

#include <iostream>
#include "algosiki.h"
using namespace std;

/**
 * Собственно, bubble_sort.
 * 
 * Внешний цикл i — "какой по счёту элемент ставим на место".
 * Внутренний цикл j — "с чем сравниваем".
 * 
 * На каждой итерации i мы пробегаем по ВСЕМУ массиву j от 0 до n-1 (а не от 0 до n-1-i, как в нормальном пузырьке),
 * и если arr[i] меньше arr[j] — меняем их местами. В итоге после внутреннего цикла arr[i] — минимальный
 * среди arr[i..n-1]. Потом i++ и всё сначала.
 * 
 * Работает? Да. Оптимально? Нет. Но зато коротко и понятно даже второкурснику.
 * 
 * Кстати, обрати внимание: в нормальном пузырьке внутренний цикл идёт до n-1-i, потому что
 * последние i элементов уже на своих местах. Тут этого нет. Мы каждый раз пробегаем весь массив.
 * Так что это даже не оптимизированный пузырёк. Это пузырёк, который не знает, что он пузырёк.
 */
void bubble_sort(Data* arr, size_t n) {
    for (size_t i = 0; i < n; i++) {
        for (size_t j = 0; j < n; j++) {
            if (arr[i].payload < arr[j].payload) swap(arr[i], arr[j]);
        }
    }
}

int main() {

    /// Стандартный ввод

    size_t n;
    cin >> n;

    Data* data = new Data[n];

    for (size_t i = 0; i < n; i++) {
        int32_t key, val;
        cin >> key >> val;
        data[i] = { key, val };
    }

    /// Стандартный ввод

    // Выводим исходный массив
    print_array(data, n, fn_print_data);
    cout << endl;

    // Вызываем сортровку
    bubble_sort(data, n);
    
    // Выводим отсортированный массив
    print_array(data, n, fn_print_data);

    return 0;
}