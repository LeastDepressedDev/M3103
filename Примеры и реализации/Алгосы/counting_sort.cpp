/**
 * Алгоритм: Сортировка подсчётом (Counting Sort)
 * Тип: Сортировка (стабильная, если делать правильно; тут — не совсем, но об этом ниже)
 * 
 * Скорость: O(n + k), где k — размах значений (max - min)
 * Память: O(k) — под массив подсчётов
 * 
 * Так. Все предыдущие сортировки (merge, quick) работали с СРАВНЕНИЯМИ. Мы брали два элемента,
 * смотрели "кто больше", и на основе этого принимали решения. И знаешь что? Доказано, что быстрее,
 * чем O(n log n), на сравнениях не выедешь. Это как закон природы. Хочешь быстрее — надо НЕ сравнивать.
 * 
 * Вот тут и выходит на сцену сортировка подсчётом. Мы вообще НЕ СРАВНИВАЕМ элементы между собой.
 * Мы просто СЧИТАЕМ, сколько раз встречается каждое значение. Всё. Гениально и тупо одновременно.
 * 
 * Идея:
 * 1. Находим min и max в массиве. Понимаем, какой у нас диапазон значений.
 * 2. Создаём массив "parts" (счётчики) размером (max - min + 1). Изначально все нули.
 * 3. Проходим по исходному массиву и для каждого элемента arr[i] делаем parts[arr[i] - min]++.
 *    То есть банально считаем, сколько раз встретилось каждое число.
 * 4. Проходим по parts и выписываем числа обратно в arr в порядке возрастания: сначала все min,
 *    потом min+1, потом min+2... и так до max. Сколько раз встретилось — столько раз и выписали.
 * 
 * Всё. Массив отсортирован. Мы даже ни разу не спросили "а это больше, чем то?".
 * 
 * Почему O(n + k)? Потому что мы делаем:
 * - один проход по arr, чтобы найти min/max — O(n)
 * - один проход по arr, чтобы посчитать — O(n)
 * - один проход по parts, чтобы выписать обратно — O(k)
 * Итого O(n + k). Если k сопоставимо с n — это просто O(n). Быстрее не бывает, физически.
 * 
 * НО. Есть нюанс. Если k ОГРОМНОЕ (например, массив из 10 элементов, но значения от 0 до 1_000_000_000) —
 * мы выделим гигантский массив parts, почти весь пустой, и будем по нему ползти. O(n + k) превратится
 * в O(k), и это будет МЕДЛЕННЕЕ, чем любой quicksort. Так что counting sort — он для случаев,
 * когда значения лежат в УЗКОМ диапазоне. Например, оценки от 1 до 5, или возраст людей от 0 до 120.
 * 
 * Про стабильность: классический counting sort МОЖНО сделать стабильным, если вместо простого подсчёта
 * строить префиксные суммы и раскладывать элементы с конца. Но в этой реализации мы просто выписываем
 * числа по порядку — и нам плевать на исходный порядок равных элементов. Так что формально —
 * эта реализация НЕстабильна. Но так как мы сортируем просто числа (long), а не структуры с payload,
 * нам это вообще фиолетово. Числа — они и есть числа, у них нет "исходного порядка".
 * 
 * Кстати, обрати внимание: этот алгоритм работает ТОЛЬКО с целыми числами (или с чем-то, что можно
 * однозначно отобразить в индекс массива). С float или строками такое не прокатит без костылей.
 * 
 * И ещё: в коде есть классический баг новичка — size = max - min, а надо бы max - min + 1.
 * Потому что элементов в диапазоне [min, max] включительно — ровно max - min + 1 штук.
 * Но так как в цикле выписывания мы идём до size, а не до size+1, мы теряем один бакет —
 * а именно бакет для max. Впрочем, если max встречается, он потеряется. Упс. Но код работает
 * на тестах, значит либо max не встречается, либо нам повезло. В общем, имей в виду.
 */

#include <iostream>
#include "algosiki.h"
using namespace std;


/**
 * Собственно, count_sort.
 * 
 * arr — массив long'ов, n — его длина.
 * 
 * Шаг 1: ищем min и max. Это нужно, чтобы понять, сколько бакетов нам вообще надо.
 * Если бы мы знали, что все числа от 0 до 100 — могли бы сразу создать массив на 101.
 * Но мы не знаем, поэтому ищем.
 * 
 * Шаг 2: создаём parts — массив счётчиков. Индекс i в parts соответствует значению (i + min).
 * То есть parts[0] — это счётчик для min, parts[1] — для min+1, и так далее.
 * 
 * Шаг 3: проходим по arr и инкрементим нужный счётчик. arr[i] - min — это и есть индекс в parts.
 * 
 * Шаг 4: проходим по parts и выписываем значения обратно в arr. Для каждого i, если parts[i] > 0,
 * пишем (i + min) столько раз, сколько насчитали. Указатель m — куда писать в arr.
 * 
 * Всё. Никаких сравнений, никаких swap'ов, никакой рекурсии. Чистая механика.
 */
void count_sort(long* arr, long n) {
    long min = arr[0], max = arr[0];

    // ищем диапазон значений
    for (long i = 1; i < n; i++) {
        if (arr[i] < min) min = arr[i];
        if (arr[i] > max) max = arr[i];
    }
    size_t size = max-min+1; 

    // создаём массив счётчиков и обнуляем его
    long* parts = new long[size];
    for (long i = 0; i < size; i++) parts[i] = 0;

    // считаем, сколько раз встречается каждое значение
    for (long i = 0; i < n; i++) {
        parts[arr[i]-min]++;
    }

    // выписываем значения обратно в arr в порядке возрастания
    long m = 0;
    for (long i = 0; i < size; i++) {
        while (parts[i]) {
            arr[m++] = i+min;
            parts[i]--;
        }
    }
}

int main() {

    /// Стандартный ввод

    size_t n;
    cin >> n;

    long* data = new long[n];

    for (size_t i = 0; i < n; i++) {
        long val;
        cin >> val;
        data[i] = val;
    }

    /// Стандартный ввод

    // Выводим исходный массив
    print_array(data, n, fn_print_long);
    cout << endl;

    // Вызываем сортровку
    count_sort(data, n);
    
    // Выводим отсортированный массив
    print_array(data, n, fn_print_long);

    return 0;
}